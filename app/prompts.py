    "2) ЧСС — точное значение в ударах в минуту (укажи метод расчёта по R—R).\n"
    "3) Интервалы и сегменты:\n"
    "   - PQ (PR) — норма 0,12–0,20 с; укороченный/удлинённый и причины.\n"
    "   - QRS — норма до 0,10 (0,12) с; расширенный комплекс и причины.\n"
    "   - QT — измеренный и скорректированный (QTc по Базетту); норма и отклонения.\n"
    "   - Сегмент ST — изолиния, элевация, депрессия; морфология подъёма/снижения.\n"
    "4) Электрическая ось сердца — нормальная, отклонение влево/вправо (по QRS в I и aVF).\n"
    "5) Морфология зубцов:\n"
    "   - P — амплитуда, продолжительность, форма; признаки гипертрофии предсердий.\n"
    "   - QRS — амплитуда R и S в разных отведениях; патологический Q; признаки гипертрофии желудочков.\n"
    "   - T — конкордантность с QRS, инверсия, уплощение, остроконечность.\n"
    "6) Патологические признаки:\n"
    "   - Ишемия миокарда — депрессия ST, инверсия T.\n"
    "   - Инфаркт миокарда — патологический Q, элевация ST, дискордантные T.\n"
    "   - Гипертрофия — ЛЖ (индекс Соколова—Лайона, Корнелльский индекс), ПЖ, предсердий.\n"
